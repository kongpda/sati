// Embeds drizzle/*.sql into src/migrations.gen.ts so the bundled CLI needs no files on disk.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../drizzle/", import.meta.url);
const files = readdirSync(dir)
  .filter((f) => f.endsWith(".sql"))
  .sort();
const entries = files.map((f, i) => {
  const sql = readFileSync(new URL(f, dir), "utf8").replaceAll("--> statement-breakpoint", "");
  return `  { version: ${i + 1}, name: ${JSON.stringify(f)}, sql: ${JSON.stringify(sql)} },`;
});
writeFileSync(
  new URL("../src/migrations.gen.ts", import.meta.url),
  `// Generated by scripts/embed-migrations.mjs from drizzle/*.sql. Do not edit.\nexport const MIGRATIONS: readonly { version: number; name: string; sql: string }[] = [\n${entries.join("\n")}\n];\n`,
);
console.log(`embedded ${files.length} migrations`);
